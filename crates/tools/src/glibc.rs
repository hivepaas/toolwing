fn class(c: u32) -> (bool, bool, i8) {
    if c > 0x10_ffff {
        // Beyond Unicode, which glibc's UTF-8 still decodes: nothing.
        return (false, false, -1);
    }
    let i = RANGES.partition_point(|r| r.0 <= c).saturating_sub(1);
    let r = RANGES[i];
    (r.1, r.2, r.3)
}

/// `iswspace`.
pub fn is_space(c: u32) -> bool {
    class(c).0
}

/// `iswprint`.
pub fn is_print(c: u32) -> bool {
    class(c).1
}

/// `iswblank`: a tab, a space, and the other spaces that do not end a line
/// (dumped from glibc as the table was).
pub fn is_blank(c: u32) -> bool {
    matches!(c, 0x09 | 0x20 | 0x1680 | 0x2000..=0x2006 | 0x2008..=0x200a | 0x205f | 0x3000)
}

/// `wcwidth`: the columns a character takes, -1 for none.
pub fn width(c: u32) -> i32 {
    i32::from(class(c).2)
}

/// What `mbrtoc32` makes of the bytes at the start of a buffer.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Decoded {
    /// A character, and how many bytes it took.
    Char(u32, usize),
    /// Not a character (`(size_t) -1`).
    Invalid,
    /// The start of one, cut by the end (`(size_t) -2`).
    Incomplete,
}

/// glibc's UTF-8, as `mbrtoc32` decodes it: the original UTF-8 of 1 to 6
/// bytes, up to 0x7FFFFFFF (code points past Unicode's last included), but
/// no overlong form and no surrogate.
pub fn mbrtoc32(b: &[u8]) -> Decoded {
    let Some(&b0) = b.first() else {
        return Decoded::Incomplete;
    };
    let (n, mut v, min) = match b0 {
        0x00..=0x7f => return Decoded::Char(u32::from(b0), 1),
        0xc2..=0xdf => (2, u32::from(b0 & 0x1f), 0x80),
        0xe0..=0xef => (3, u32::from(b0 & 0x0f), 0x800),
        0xf0..=0xf7 => (4, u32::from(b0 & 0x07), 0x1_0000),
        0xf8..=0xfb => (5, u32::from(b0 & 0x03), 0x20_0000),
        0xfc..=0xfd => (6, u32::from(b0 & 0x01), 0x400_0000),
        _ => return Decoded::Invalid,
    };
    for i in 1..n {
        let Some(&c) = b.get(i) else {
            return Decoded::Incomplete;
        };
        if c & 0xc0 != 0x80 {
            return Decoded::Invalid;
        }
        v = (v << 6) | u32::from(c & 0x3f);
    }
    if v < min || (0xd800..=0xdfff).contains(&v) {
        return Decoded::Invalid;
    }
    Decoded::Char(v, n)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn as_glibc_sees_them() {
        assert!(is_space(0x20) && is_space(0x3000) && !is_space(0xa0));
        assert!(is_print(0x61) && !is_print(0x85) && is_print(0xe9));
        assert_eq!(
            (width(0x61), width(0x4e2d), width(0x301), width(0x0a)),
            (1, 2, 0, -1)
        );
        assert_eq!(width(0x11_0000), -1);
    }

    #[test]
    fn decodes_as_glibc() {
        assert_eq!(mbrtoc32("é".as_bytes()), Decoded::Char(0xe9, 2));
        assert_eq!(mbrtoc32(b"\xf4\x90\x80\x80"), Decoded::Char(0x11_0000, 4));
        assert_eq!(
            mbrtoc32(b"\xf8\x88\x80\x80\x80"),
            Decoded::Char(0x20_0000, 5)
        );
        assert_eq!(mbrtoc32(b"\xed\xa0\x80"), Decoded::Invalid);
        assert_eq!(mbrtoc32(b"\xc0\xaf"), Decoded::Invalid);
        assert_eq!(mbrtoc32(b"\xe0\x80\xaf"), Decoded::Invalid);
        assert_eq!(mbrtoc32(b"\xe2\x82"), Decoded::Incomplete);
        assert_eq!(mbrtoc32(b"\xe2\x82a"), Decoded::Invalid);
    }
}
